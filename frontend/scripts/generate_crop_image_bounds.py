"""Generate browser view boxes from the visible pixels of crop PNG assets."""

import json
from pathlib import Path

from PIL import Image


FRONTEND = Path(__file__).resolve().parents[1]
ASSETS = FRONTEND / "public" / "garden" / "assets" / "crops"
OUTPUT = FRONTEND / "public" / "garden" / "crop-image-bounds.js"
PADDING = 4


def image_bounds(path: Path) -> dict[str, str | int]:
    with Image.open(path) as image:
        alpha = image.convert("RGBA").getchannel("A")
        visible = alpha.point(lambda value: 255 if value > 128 else 0).getbbox()
        if visible is None:
            raise ValueError(f"No visible crop artwork: {path}")
        left, top, right, bottom = visible
        left = max(0, left - PADDING)
        top = max(0, top - PADDING)
        right = min(image.width, right + PADDING)
        bottom = min(image.height, bottom + PADDING)
        return {
            "viewBox": f"{left} {top} {right - left} {bottom - top}",
            "width": image.width,
            "height": image.height,
        }


def main() -> None:
    bounds = {path.stem: image_bounds(path) for path in sorted(ASSETS.glob("*.png"))}
    OUTPUT.write_text(
        "// Generated by frontend/scripts/generate_crop_image_bounds.py.\n"
        + "window.GardenCropBounds = Object.freeze("
        + json.dumps(bounds, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        + ");\n",
        encoding="utf-8",
    )
    print(f"Generated view boxes for {len(bounds)} crop images.")


if __name__ == "__main__":
    main()
